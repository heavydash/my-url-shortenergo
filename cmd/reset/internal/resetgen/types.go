// Пакет resetgen реализует генерацию методов Reset() для Go-структур.
//
// Генератор анализирует исходный код, находит структуры, помеченные маркером
// //generate:reset, и создаёт для них методы Reset(), сбрасывающие все поля
// в нулевые значения. Это полезно для пулинга объектов и переиспользования памяти.
package resetgen

// ResetTarget представляет цель для генерации — структуру, помеченную маркером.
//
// Содержит всю необходимую информацию о структуре:
//   - путь к пакету для генерации файла в правильном месте
//   - имя пакета и самой структуры
//   - список полей с их типами и классификацией
type ResetTarget struct {
	PkgPath string        // полный путь к пакету (для создания файла)
	PkgName string        // имя пакета (для объявления package)
	Name    string        // имя структуры
	Fields  []StructField // список полей структуры
}

// StructField представляет одно поле структуры.
//
// Хранит имя поля, его строковое представление типа и классификацию,
// которая определяет, как именно нужно сбрасывать это поле.
type StructField struct {
	Name string    // имя поля
	Type string    // строковое представление типа (например, "[]string")
	Kind FieldKind // классификация типа для выбора стратегии сброса
}

// FieldKind классифицирует тип поля для выбора стратегии сброса.
//
// Разные типы требуют разного подхода при сбросе:
//   - примитивы: просто присвоить нулевое значение
//   - слайсы: очистить через [:0] или nil
//   - мапы: создать новую пустую мапу
//   - указатели: обнулить или рекурсивно сбросить
//   - структуры: рекурсивно вызвать Reset(), если он есть
type FieldKind int

const (
	// KindPrimitive — базовые типы (int, string, bool, time.Time и т.д.)
	// Сбрасываются присваиванием нулевого значения.
	KindPrimitive FieldKind = iota

	// KindPointer — указатели на любые типы
	// Сбрасываются присваиванием nil.
	KindPointer

	// KindSlice — слайсы ([]T)
	// Сбрасываются либо через [:0] (если нужно сохранить память),
	// либо присваиванием nil.
	KindSlice

	// KindMap — мапы (map[K]V)
	// Сбрасываются созданием новой пустой мапы через make().
	KindMap

	// KindStruct — встроенные структуры (используется редко)
	// Требуют рекурсивного сброса полей.
	KindStruct

	// KindUnknown — нераспознанный тип
	// Используется как запасной вариант.
	KindUnknown

	// KindEmbeddedStruct — встроенная структура (anonymous field)
	// Требует особой обработки при генерации.
	KindEmbeddedStruct

	// KindNamedStruct — именованная структура из этого же или другого пакета
	// Может иметь свой метод Reset(), который нужно вызвать.
	KindNamedStruct
)
