// Пакет pool реализует обобщённый пул объектов с автоматическим сбросом состояния.
//
// Пул позволяет переиспользовать объекты, уменьшая количество аллокаций памяти
// и нагрузку на сборщик мусора. Перед возвратом в пул каждый объект автоматически
// сбрасывается в начальное состояние через вызов метода Reset().
package pool

import "sync"

// Resettable определяет интерфейс для объектов, которые могут сбрасывать своё состояние.
//
// Любой тип, который хочет использоваться в Pool, должен реализовывать этот интерфейс.
// Метод Reset() должен возвращать объект в состояние, эквивалентное только что созданному
// (нулевые значения для всех полей).
type Resettable interface {
	Reset()
}

// Pool представляет собой типобезопасный пул переиспользуемых объектов.
//
// Параметр T — любой тип, реализующий интерфейс Resettable.
// Пул гарантирует, что:
//   - При получении объект готов к использованию (уже сброшен)
//   - При возврате объект автоматически сбрасывается
//
// Пример использования:
//
//	type MyStruct struct {
//	    Data []byte
//	}
//
//	func (m *MyStruct) Reset() {
//	    m.Data = m.Data[:0]
//	}
//
//	pool := New(func() *MyStruct {
//	    return &MyStruct{Data: make([]byte, 0, 1024)}
//	})
//
//	obj := pool.Get()
//	defer pool.Put(obj)
type Pool[T Resettable] struct {
	pool sync.Pool
}

// New создаёт новый пул объектов с заданной функцией создания.
//
// Параметры:
//   - newFn: функция, которая создаёт новый объект типа T
//
// Возвращает: инициализированный пул.
//
// Важно: при создании объекта через newFn сразу вызывается Reset(),
// чтобы гарантировать, что все объекты в пуле находятся в сброшенном состоянии.
func New[T Resettable](newFn func() T) *Pool[T] {
	return &Pool[T]{
		pool: sync.Pool{
			New: func() any {
				obj := newFn()
				obj.Reset()
				return obj
			},
		},
	}
}

// Get извлекает объект из пула.
//
// Если в пуле есть свободные объекты, возвращается один из них.
// Если пул пуст, создаётся новый объект с помощью функции, переданной в New().
//
// Возвращает: объект типа T, готовый к использованию (уже сброшенный).
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put возвращает объект обратно в пул для повторного использования.
//
// Перед возвратом у объекта автоматически вызывается Reset(),
// чтобы очистить состояние для следующего пользователя.
//
// Параметры:
//   - obj: объект, который возвращается в пул
//
// После вызова Put объект не должен использоваться вызывающим кодом,
// так как он может быть выдан другому потребителю.
func (p *Pool[T]) Put(obj T) {
	obj.Reset()
	p.pool.Put(obj)
}
