// Пакет models содержит модели данных для проекта сокращателя URL.
//
// Структуры в этом пакете могут быть помечены специальным маркером
// для автоматической генерации метода Reset(), который сбрасывает
// состояние объекта к начальным значениям.
package models

import "time"

// ShortLink представляет сокращённую ссылку в системе.
//
// generate:reset — маркер для генерации метода Reset().
// При генерации будут созданы методы:
//   - Reset() — сбрасывает все поля структуры к нулевым значениям
//   - NewShortLink() — конструктор, возвращающий новый экземпляр
//
// Поля структуры:
//   - ID: уникальный идентификатор ссылки в БД
//   - Short: короткий код ссылки (например, "abc123")
//   - Original: оригинальный длинный URL
//   - Clicks: счётчик переходов по ссылке
//   - CreatedAt: время создания ссылки
//   - Tags: список тегов для категоризации
//   - Meta: дополнительные метаданные в формате ключ-значение

// generate:reset
type ShortLink struct {
	ID        uint64            // уникальный идентификатор
	Short     string            // короткий код
	Original  string            // оригинальный URL
	Clicks    int64             // счётчик кликов
	CreatedAt time.Time         // время создания
	Tags      []string          // теги
	Meta      map[string]string // метаданные
}
