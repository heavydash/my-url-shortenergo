// Package model предоставляет структуры данных для URL shortener сервиса.
package model

// Request представляет запрос на сокращение одиночного URL.
//
// Используется в эндпоинтах:
//   - POST / (text/plain) - тело запроса содержит просто URL
//   - POST /api/shorten (application/json) - JSON с полем "url"
//
// Пример JSON запроса:
//
//	{
//	  "url": "https://example.com/very/long/path"
//	}
type Request struct {
	// URL содержит оригинальный (длинный) URL для сокращения.
	//
	// Валидация:
	//   - Должен начинаться с http:// или https://
	//   - Должен быть валидным URL согласно RFC 3986
	//   - Длина ограничена возможностями БД (обычно 2000+ символов)
	//
	// Примеры валидных URL:
	//   - "https://example.com"
	//   - "http://localhost:8080/path"
	//   - "https://api.example.com/v1/users?active=true"
	//
	// Особенности обработки:
	//   - Сервер может нормализовать URL (убирать лишние слеши)
	//   - Query параметры и anchors сохраняются
	//   - Протокол регистр-независимый (HTTP, http, HtTp)
	URL string `json:"url"`
}

// Response представляет ответ на запрос сокращения URL.
//
// Используется в JSON ответах эндпоинтов:
//   - POST /api/shorten - успешное сокращение
//   - POST /api/shorten/batch - каждый элемент массива
//   - Все эндпоинты при ошибках (с заполненным полем Error)
//
// Пример успешного JSON ответа:
//
//	{
//	  "result": "http://short.ly/abc123"
//	}
//
// Пример ошибочного JSON ответа:
//
//	{
//	  "error": "invalid URL format"
//	}
type Response struct {

	// Result содержит сокращенный URL при успешном выполнении.
	//
	// Формат: {base_url}/{short_id}
	// Пример: "http://short.ly/abc123"
	//
	// JSON тег `omitempty` означает:
	//   - Поле исключается из JSON если пустое
	//   - Всегда присутствует при успешном ответе
	//   - Отсутствует при ошибках
	Result string `json:"result,omitempty"`

	// Error содержит сообщение об ошибке при неудачном выполнении.
	//
	// Формат: читаемое человеком описание ошибки на английском
	// или языке, соответствующем Accept-Language заголовку.
	//
	// Примеры значений:
	//   - "invalid URL format"
	//   - "URL already shortened"
	//   - "internal server error"
	//
	// Особенности:
	//   - Всегда присутствует при ошибках (HTTP статус 4xx/5xx)
	//   - Отсутствует при успешном выполнении
	//   - Не содержит чувствительной информации (пути, токены)
	//   - Может использоваться для локализации на клиенте
	Error string `json:"error,omitempty"`
}
