// Package service предоставляет интерфейсы и реализации сервиса аудита.
// Пакет реализует паттерн "фасад" для упрощенного доступа к аудит-функциональности
// с поддержкой noop-реализаций для случаев когда аудит отключен.
package service

import (
	"context"

	"github.com/heavydash/my-url-shortenergo/internal/audit"
	"github.com/heavydash/my-url-shortenergo/internal/config"
	"go.uber.org/zap"
)

// Service определяет основной контракт сервиса аудита.
//
// Интерфейс предоставляет минимальный набор методов для интеграции аудита
// в приложение. Реализации должны обеспечивать:
//   - Асинхронную обработку событий (не блокирующую основной поток)
//   - Надежную доставку событий в настроенные системы
//   - Graceful shutdown для корректного завершения работы
//
// Реализации интерфейса:
//   - AuditService: полнофункциональная асинхронная реализация
//   - Noop: пустая реализация для случаев когда аудит отключен
//   - SyncService: синхронная реализация для тестов (если требуется)
//
// Пример использования через интерфейс:
//
//	// Инициализация (обычно в main или di контейнере)
//	var auditSvc service.Service
//	if cfg.EnableAudit {
//	    auditSvc = service.NewAuditService(cfg, logger)
//	} else {
//	    auditSvc = service.Noop{}
//	}
//
//	// Использование в бизнес-логике
//	func processRequest(req Request, auditSvc service.Service) {
//	    // ... обработка
//	    event := audit.NewEvent("process", req.ID)
//	    auditSvc.SendAsync(event) // не блокирует
//	    // ... продолжение
//	}
//
// Примечания:
//   - Все методы интерфейса должны быть thread-safe
//   - SendAsync не должен паниковать при любых входных данных
//   - Shutdown должен быть идемпотентным
type Service interface {
	// SendAsync асинхронно отправляет аудит-событие на обработку.
	//
	// Метод предназначен для максимальной производительности - он не должен
	// блокировать вызывающую горутину. Реализации могут:
	//   - Помещать событие в буферизированную очередь (AuditService)
	//   - Игнорировать событие (Noop)
	//   - Отправлять событие синхронно (только для тестов)
	//
	// Параметры:
	//   - event: аудит-событие для записи. Реализации должны корректно
	//            обрабатывать nil события (игнорировать или логировать).
	//
	// Гарантии:
	//   - Метод возвращается немедленно (не блокирует)
	//   - Событие будет обработано (если сервис активен)
	//   - Ошибки отправки логируются внутри реализации
	//   - Thread-safe (безопасен для конкурентных вызовов)
	//
	// Пример использования:
	//     // В HTTP обработчике
	//     func shortenHandler(w http.ResponseWriter, r *http.Request) {
	//         // ... валидация
	//         event := audit.NewShortenEvent(userID, url)
	//         auditSvc.SendAsync(event) // <-- не блокирует ответ
	//         // ... формирование ответа
	//     }
	SendAsync(event *audit.Event)
	// Shutdown выполняет graceful shutdown сервиса аудита.
	//
	// Метод должен гарантировать:
	//   1. Прекращение приема новых событий
	//   2. Обработку всех уже принятых событий
	//   3. Корректное освобождение ресурсов (файлы, соединения)
	//   4. Возврат управления не дольше указанного таймаута
	//
	// Параметры:
	//   - ctx: контекст с таймаутом для ограничения времени shutdown.
	//          Если контекст истекает, метод должен вернуть ошибку,
	//          но продолжить освобождение ресурсов в фоне.
	//
	// Возвращает:
	//   - error: ошибка если shutdown не завершился в указанный таймаут.
	//            nil если shutdown выполнен успешно.
	//
	// Особенности:
	//   - Метод должен быть идемпотентным (повторные вызовы безопасны)
	//   - После Shutdown() вызовы SendAsync() должны игнорироваться
	//   - Рекомендуется вызывать Shutdown() при получении SIGTERM/SIGINT
	//
	// Пример graceful shutdown:
	//     // Обработка сигналов завершения
	//     ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	//     defer cancel()
	//
	//     if err := auditSvc.Shutdown(ctx); err != nil {
	//         logger.Error("audit shutdown failed", zap.Error(err))
	//         // возможно, форсированное завершение
	//     }
	Shutdown(ctx context.Context) error
}

// New создает экземпляр сервиса аудита на основе конфигурации.
//
// Фабричная функция реализует паттерн "фабрика" и выполняет:
//   - Анализ конфигурации: проверяет наличие настроенных sender'ов
//   - Выбор реализации: AuditService или Noop
//   - Инициализацию: запуск фоновых процессов для AuditService
//
// Параметры:
//   - cfg: конфигурация приложения. Проверяются поля:
//     AuditFilePath (путь к файлу) и AuditRemoteURL (HTTP эндпоинт)
//   - logger: логгер для записи операционных событий сервиса
//
// Возвращает:
//   - Service: готовый к использованию сервис аудита.
//     Если оба поля конфигурации пустые - возвращает Noop.
//
// Пример использования:
//
//	// Загрузка конфигурации
//	cfg := config.Load()
//
//	// Создание сервиса (автоматически выбирается реализация)
//	auditSvc := service.New(cfg, logger)
//	defer auditSvc.Shutdown(context.Background())
//
//	// Единообразное использование независимо от реализации
//	auditSvc.SendAsync(event)
//
// Преимущества:
//   - Единая точка инициализации
//   - Автоматический выбор реализации
//   - Упрощенная интеграция в приложение
//   - Возможность отключения аудита через конфигурацию
//
// Примечания:
//   - Функция не возвращает ошибку - проблемы инициализации логируются
//   - Рекомендуется вызывать Shutdown() при завершении приложения
//   - Noop реализация не потребляет ресурсы и не имеет overhead
func New(cfg *config.Config, logger *zap.Logger) Service {
	if cfg.AuditFilePath == "" && cfg.AuditRemoteURL == "" {
		return Noop{}
	}

	return NewAuditService(cfg, logger)
}

// Noop представляет пустую (no-operation) реализацию сервиса аудита.
//
// Особенности:
//   - Все методы являются no-op (ничего не делают)
//   - Не потребляет память и CPU ресурсы
//   - Не создает фоновых горутин
//   - Не требует вызова Shutdown()
//
// Используется в случаях:
//   - Аудит отключен в конфигурации
//   - Unit-тесты для изоляции
//   - Development окружение без необходимости аудита
//   - Feature flags для временного отключения аудита
//
// Пример использования:
//
//	// Конфигурационное отключение аудита
//	type Config struct {
//	    EnableAudit bool `env:"ENABLE_AUDIT"`
//	}
//
//	func NewService(cfg Config) service.Service {
//	    if !cfg.EnableAudit {
//	        return service.Noop{}
//	    }
//	    return service.NewAuditService(...)
//	}
//
// Производительность:
//   - SendAsync: O(1), только проверка указателя
//   - Shutdown: O(1), всегда возвращает nil
//   - Память: 0 байт (empty struct)
//
// Примечания:
//   - Является zero-value (можно использовать var svc service.Noop)
//   - Thread-safe (не имеет состояния)
//   - Можно использовать как заглушку в тестах
type Noop struct{}

// SendAsync игнорирует переданное аудит-событие.
// Реализация no-op для случаев когда аудит не требуется.
//
// Метод существует для удовлетворения интерфейса Service
// и позволяет коду, зависящему от аудита, работать без изменений
// даже когда аудит отключен.
//
// Параметры:
//   - event: аудит-событие (игнорируется, может быть nil)
//
// Пример:
//
//	// Этот код работает одинаково для AuditService и Noop
//	func businessLogic(auditSvc service.Service) {
//	    // ... логика
//	    auditSvc.SendAsync(event) // для Noop - no-op
//	    // ... продолжение
//	}
func (Noop) SendAsync(_ *audit.Event) {}

// Shutdown ничего не делает и немедленно возвращает nil.
// Реализация no-op для совместимости с интерфейсом Service.
//
// Метод позволяет вызывать Shutdown() для Noop сервиса без
// дополнительных проверок типа. Это упрощает код завершения
// приложения.
//
// Параметры:
//   - ctx: контекст (игнорируется)
//
// Возвращает:
//   - error: всегда nil
//
// Пример:
//
//	// Универсальный код shutdown
//	func cleanup(auditSvc service.Service) {
//	    // Не нужно проверять тип сервиса
//	    ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
//	    defer cancel()
//	    auditSvc.Shutdown(ctx) // безопасно для Noop
//	}
func (Noop) Shutdown(_ context.Context) error { return nil }
