// Package idgen предоставляет функции для генерации уникальных идентификаторов.
// Идентификаторы используются для создания коротких ссылок в URL shortener сервисе.
package idgen

import (
	"crypto/rand"
	"log"
)

// charset содержит символы, используемые для генерации идентификаторов.
// Включает буквы латинского алфавита в верхнем и нижнем регистре, а также цифры.
const charset = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"

// IDGen генерирует случайный идентификатор длиной 8 символов.
//
// Идентификатор генерируется с использованием криптографически безопасного
// генератора случайных чисел (crypto/rand) и содержит только символы из
// набора [a-zA-Z0-9].
//
// Пример сгенерированного ID: "aB3dEfG7"
//
// Возвращает:
//   - string: сгенерированный идентификатор
//   - error: ошибка, если не удалось получить случайные байты
//
// Использование:
//
//	id, err := idgen.IDGen()
//	if err != nil {
//	    log.Fatalf("Failed to generate ID: %v", err)
//	}
//	fmt.Printf("Generated ID: %s", id)
//
// Примечания:
//   - Длина идентификатора фиксирована и составляет 8 символов
//   - Всего возможно 62^8 ≈ 218 триллионов уникальных комбинаций
//   - Функция логирует сгенерированный ID для отладки
//   - Для обеспечения уникальности в продакшене рекомендуется проверять
//     сгенерированный ID на коллизии в хранилище
func IDGen() (string, error) {
	b := make([]byte, 8)
	_, err := rand.Read(b)
	if err != nil {
		return "", err
	}
	for i := range b {
		b[i] = charset[int(b[i])%len(charset)]
	}
	id := string(b)
	log.Printf("Generated ID: %s", id)
	return id, nil
}
